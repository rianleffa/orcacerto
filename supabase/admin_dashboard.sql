-- Admin status comes from Supabase Auth's authoritative, confirmed email.
-- No client-editable profile field or user metadata can grant admin access.
CREATE OR REPLACE FUNCTION public.is_site_admin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM auth.users AS auth_user
    WHERE auth_user.id = (SELECT auth.uid())
      AND lower(auth_user.email) = 'rianleffa5@gmail.com'
      AND auth_user.email_confirmed_at IS NOT NULL
      AND auth_user.deleted_at IS NULL
  );
$$;

REVOKE ALL ON FUNCTION public.is_site_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_site_admin() TO authenticated;

-- One row per browser tab session per local calendar day. The browser sends
-- random IDs; the database supplies identity (when signed in) and timestamp.
CREATE TABLE IF NOT EXISTS public.site_access_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id UUID NOT NULL,
  visit_id UUID NOT NULL,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  access_date DATE NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT site_access_events_visit_day_key UNIQUE (visit_id, access_date)
);

CREATE INDEX IF NOT EXISTS site_access_events_occurred_at_idx
  ON public.site_access_events (occurred_at DESC);
CREATE INDEX IF NOT EXISTS site_access_events_user_occurred_at_idx
  ON public.site_access_events (user_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS site_access_events_visitor_occurred_at_idx
  ON public.site_access_events (visitor_id, occurred_at DESC);

ALTER TABLE public.site_access_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "site_access_events_select_admin" ON public.site_access_events;
CREATE POLICY "site_access_events_select_admin"
  ON public.site_access_events
  FOR SELECT
  TO authenticated
  USING ((SELECT public.is_site_admin()));

REVOKE ALL ON TABLE public.site_access_events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.site_access_events TO authenticated;
REVOKE ALL ON SEQUENCE public.site_access_events_id_seq FROM PUBLIC, anon, authenticated;

-- This public RPC accepts only random analytics identifiers. Authenticated
-- identity is always taken from the verified JWT; callers cannot pass a user ID
-- or timestamp. Duplicate reloads in the same tab/day are idempotent.
CREATE OR REPLACE FUNCTION public.record_site_visit(
  p_visitor_id UUID,
  p_visit_id UUID
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  current_user_id UUID := auth.uid();
  session_claim TEXT := auth.jwt() ->> 'session_id';
  inserted_rows INTEGER := 0;
BEGIN
  IF p_visitor_id IS NULL OR p_visit_id IS NULL THEN
    RETURN FALSE;
  END IF;

  IF current_user_id IS NOT NULL AND coalesce(session_claim, '') = '' THEN
    RETURN FALSE;
  END IF;

  INSERT INTO public.site_access_events (visitor_id, visit_id, user_id, access_date)
  VALUES (
    p_visitor_id,
    p_visit_id,
    current_user_id,
    (now() AT TIME ZONE 'America/Sao_Paulo')::DATE
  )
  ON CONFLICT (visit_id, access_date) DO UPDATE
    SET user_id = coalesce(public.site_access_events.user_id, EXCLUDED.user_id)
    WHERE public.site_access_events.user_id IS NULL
      AND EXCLUDED.user_id IS NOT NULL
      AND public.site_access_events.visitor_id = EXCLUDED.visitor_id;

  GET DIAGNOSTICS inserted_rows = ROW_COUNT;
  RETURN inserted_rows > 0;
END;
$$;

REVOKE ALL ON FUNCTION public.record_site_visit(UUID, UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.record_site_visit(UUID, UUID) TO anon, authenticated;

