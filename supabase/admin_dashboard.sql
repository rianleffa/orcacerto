CREATE OR REPLACE FUNCTION public.get_admin_dashboard(
  p_period TEXT DEFAULT 'week',
  p_search TEXT DEFAULT '',
  p_page INTEGER DEFAULT 1
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
SET timezone = 'America/Sao_Paulo'
AS $$
DECLARE
  selected_period TEXT := lower(coalesce(p_period, 'week'));
  search_term TEXT := left(btrim(coalesce(p_search, '')), 100);
  current_page INTEGER := greatest(coalesce(p_page, 1), 1);
  page_size CONSTANT INTEGER := 50;
  period_start TIMESTAMPTZ;
  current_time_at_db TIMESTAMPTZ := now();
  bucket_unit TEXT;
  bucket_step INTERVAL;
  total_users BIGINT;
  period_accesses BIGINT;
  period_unique_users BIGINT;
  period_anonymous_visitors BIGINT;
  period_new_users BIGINT;
  total_matching_users BIGINT;
  latest_access TIMESTAMPTZ;
  chart_rows JSONB;
  user_rows JSONB;
BEGIN
  IF NOT public.is_site_admin() THEN
    RAISE EXCEPTION 'Acesso administrativo negado.' USING ERRCODE = '42501';
  END IF;

  IF selected_period NOT IN ('day', 'week', 'month') THEN
    selected_period := 'week';
  END IF;

  period_start := date_trunc(selected_period, current_time_at_db);
  IF selected_period = 'day' THEN
    bucket_unit := 'hour';
    bucket_step := INTERVAL '1 hour';
  ELSE
    bucket_unit := 'day';
    bucket_step := INTERVAL '1 day';
  END IF;

  SELECT count(*)
  INTO total_users
  FROM auth.users AS auth_user
  WHERE auth_user.deleted_at IS NULL;

  SELECT count(*)
  INTO period_new_users
  FROM auth.users AS auth_user
  WHERE auth_user.deleted_at IS NULL
    AND auth_user.created_at >= period_start
    AND auth_user.created_at <= current_time_at_db;

  SELECT
    count(*),
    count(DISTINCT CASE
      WHEN access_event.user_id IS NOT NULL THEN 'user:' || access_event.user_id::TEXT
      ELSE 'visitor:' || access_event.visitor_id::TEXT
    END),
    count(DISTINCT access_event.visitor_id) FILTER (WHERE access_event.user_id IS NULL)
  INTO period_accesses, period_unique_users, period_anonymous_visitors
  FROM public.site_access_events AS access_event
  WHERE access_event.occurred_at >= period_start
    AND access_event.occurred_at <= current_time_at_db;

  SELECT max(access_event.occurred_at)
  INTO latest_access
  FROM public.site_access_events AS access_event;

  WITH buckets AS (
    SELECT generate_series(
      date_trunc(bucket_unit, period_start),
      date_trunc(bucket_unit, current_time_at_db),
      bucket_step
    ) AS bucket_start
  ), activity AS (
    SELECT
      date_trunc(bucket_unit, access_event.occurred_at) AS bucket_start,
      count(*) AS accesses,
      count(DISTINCT CASE
        WHEN access_event.user_id IS NOT NULL THEN 'user:' || access_event.user_id::TEXT
        ELSE 'visitor:' || access_event.visitor_id::TEXT
      END) AS unique_users,
      count(DISTINCT access_event.visitor_id) FILTER (WHERE access_event.user_id IS NULL) AS anonymous_visitors
    FROM public.site_access_events AS access_event
    WHERE access_event.occurred_at >= period_start
      AND access_event.occurred_at <= current_time_at_db
    GROUP BY date_trunc(bucket_unit, access_event.occurred_at)
  )
  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object(
        'label', CASE
          WHEN selected_period = 'day' THEN to_char(buckets.bucket_start, 'HH24:00')
          WHEN selected_period = 'week' THEN to_char(buckets.bucket_start, 'DD/MM')
          ELSE to_char(buckets.bucket_start, 'DD')
        END,
        'accesses', coalesce(activity.accesses, 0),
        'uniqueUsers', coalesce(activity.unique_users, 0),
        'anonymousVisitors', coalesce(activity.anonymous_visitors, 0)
      ) ORDER BY buckets.bucket_start
    ),
    '[]'::JSONB
  )
  INTO chart_rows
  FROM buckets
  LEFT JOIN activity USING (bucket_start);

  SELECT count(*)
  INTO total_matching_users
  FROM auth.users AS auth_user
  LEFT JOIN public.profiles AS profile ON profile.user_id = auth_user.id
  WHERE auth_user.deleted_at IS NULL
    AND (
      search_term = ''
      OR coalesce(
        nullif(btrim(profile.full_name), ''),
        nullif(btrim(profile.name), ''),
        nullif(btrim(auth_user.raw_user_meta_data ->> 'full_name'), ''),
        nullif(btrim(auth_user.raw_user_meta_data ->> 'name'), ''),
        'Sem nome'
      ) ILIKE '%' || search_term || '%'
      OR coalesce(auth_user.email, '') ILIKE '%' || search_term || '%'
      OR coalesce(profile.city, '') ILIKE '%' || search_term || '%'
      OR coalesce(profile.state, '') ILIKE '%' || search_term || '%'
    );

  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', users.id,
        'name', users.name,
        'email', users.email,
        'createdAt', users.created_at,
        'lastAccess', users.last_access,
        'city', users.city,
        'state', users.state
      ) ORDER BY users.created_at DESC
    ),
    '[]'::JSONB
  )
  INTO user_rows
  FROM (
    SELECT
      auth_user.id,
      coalesce(
        nullif(btrim(profile.full_name), ''),
        nullif(btrim(profile.name), ''),
        nullif(btrim(auth_user.raw_user_meta_data ->> 'full_name'), ''),
        nullif(btrim(auth_user.raw_user_meta_data ->> 'name'), ''),
        'Sem nome'
      ) AS name,
      auth_user.email,
      auth_user.created_at,
      last_access.occurred_at AS last_access,
      nullif(btrim(profile.city), '') AS city,
      nullif(btrim(profile.state), '') AS state
    FROM auth.users AS auth_user
    LEFT JOIN public.profiles AS profile ON profile.user_id = auth_user.id
    LEFT JOIN LATERAL (
      SELECT max(access_event.occurred_at) AS occurred_at
      FROM public.site_access_events AS access_event
      WHERE access_event.user_id = auth_user.id
    ) AS last_access ON TRUE
    WHERE auth_user.deleted_at IS NULL
      AND (
        search_term = ''
        OR coalesce(
          nullif(btrim(profile.full_name), ''),
          nullif(btrim(profile.name), ''),
          nullif(btrim(auth_user.raw_user_meta_data ->> 'full_name'), ''),
          nullif(btrim(auth_user.raw_user_meta_data ->> 'name'), ''),
          'Sem nome'
        ) ILIKE '%' || search_term || '%'
        OR coalesce(auth_user.email, '') ILIKE '%' || search_term || '%'
        OR coalesce(profile.city, '') ILIKE '%' || search_term || '%'
        OR coalesce(profile.state, '') ILIKE '%' || search_term || '%'
      )
    ORDER BY auth_user.created_at DESC
    OFFSET (current_page - 1) * page_size
    LIMIT page_size
  ) AS users;

  RETURN jsonb_build_object(
    'period', selected_period,
    'metrics', jsonb_build_object(
      'totalUsers', total_users,
      'accesses', period_accesses,
      'uniqueUsers', period_unique_users,
      'anonymousVisitors', period_anonymous_visitors,
      'newUsers', period_new_users,
      'lastAccess', latest_access
    ),
    'chart', chart_rows,
    'users', user_rows,
    'userCount', total_matching_users,
    'page', current_page,
    'pageSize', page_size
  );
END;
$$;

REVOKE ALL ON FUNCTION public.get_admin_dashboard(TEXT, TEXT, INTEGER) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_admin_dashboard(TEXT, TEXT, INTEGER) TO authenticated;
